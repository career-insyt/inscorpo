export function searchSkillsCatalog(query: string, limit = 25): string[] {
  const q = query.trim().toLowerCase();
  if (!q) return INSYT_SKILLS_CATALOG.slice(0, limit);

  const exactMatches: string[] = [];
  const startsWithMatches: string[] = [];
  const containsMatches: string[] = [];

  for (const skill of INSYT_SKILLS_CATALOG) {
    const lower = skill.toLowerCase();
    if (lower === q) {
      exactMatches.push(skill);
    } else if (lower.startsWith(q)) {
      startsWithMatches.push(skill);
    } else if (lower.includes(q)) {
      containsMatches.push(skill);
    }
  }

  return [...exactMatches, ...startsWithMatches, ...containsMatches].slice(0, limit);
}

export function isSkillInCatalog(skillName: string): boolean {
  const target = skillName.trim().toLowerCase();
  return INSYT_SKILLS_CATALOG.some((s) => s.toLowerCase() === target);
}
